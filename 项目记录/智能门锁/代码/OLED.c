/*==================== I2C硬件初始化 ====================*/
/*
 * 函数：My_I2C_Init
 * 功能：初始化硬件I2C1，PB6=SCL时钟线、PB7=SDA数据线，作为与OLED通信的总线
 */
void My_I2C_Init(void)
{
	GPIO_InitTypeDef GPIO_InitStruct;
	I2C_InitTypeDef I2C_InitStruct;

	RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOB,ENABLE);   /* 使能GPIOB端口时钟 */
	RCC_APB1PeriphClockCmd(RCC_APB1Periph_I2C1,ENABLE);    /* 使能I2C1时钟（I2C1挂在APB1总线） */

	/* PB6=SCL, PB7=SDA 配置为复用开漏输出（I2C总线必须开漏，靠上拉电阻拉成高电平） */
	GPIO_InitStruct.GPIO_Pin=GPIO_Pin_6|GPIO_Pin_7;
	GPIO_InitStruct.GPIO_Mode=GPIO_Mode_AF_OD;
	GPIO_InitStruct.GPIO_Speed=GPIO_Speed_50MHz;
	GPIO_Init(GPIOB,&GPIO_InitStruct);
	GPIO_SetBits(GPIOB,GPIO_Pin_6|GPIO_Pin_7);   /* 先把两线置高，保证总线空闲为高电平 */

	I2C_InitStruct.I2C_ClockSpeed=100000;                  /* 总线时钟100kHz标准模式 */
	I2C_InitStruct.I2C_Mode=I2C_Mode_I2C;
	I2C_InitStruct.I2C_AcknowledgedAddress=I2C_AcknowledgedAddress_7bit;  /* 采用7位地址寻址 */
	I2C_InitStruct.I2C_DutyCycle=I2C_DutyCycle_2;
	I2C_InitStruct.I2C_OwnAddress1=0x00;
	I2C_InitStruct.I2C_Ack=I2C_Ack_Enable;                 /* 使能应答ACK */
	I2C_Init(I2C1,&I2C_InitStruct);
	I2C_Cmd(I2C1,ENABLE);                                 /* 使能I2C1外设 */
}

/*==================== I2C发送一帧数据 ====================*/
/*
 * 函数：My_I2C_SendBytes
 * 功能：通过指定I2C外设向从机发送一帧数据（起始->地址->数据->停止）
 * 参数：I2Cx=I2C外设；Addr=从机地址；pData=待发数据缓冲区；Size=发送字节数
 * 返回：0=成功；-1=地址阶段无应答(AF)；-2=数据阶段无应答(AF)
 */
int My_I2C_SendBytes(I2C_TypeDef *I2Cx,uint8_t Addr,uint8_t *pData,uint16_t Size)
{
	uint16_t i;
	while(I2C_GetFlagStatus(I2Cx,I2C_FLAG_BUSY)==SET);  /* 等待总线空闲：BUSY=SET表示忙，循环直到空闲 */
	I2C_GenerateSTART(I2Cx,ENABLE);                     /* 发送起始信号 */
	while(I2C_GetFlagStatus(I2Cx,I2C_FLAG_SB)==RESET);   /* 等待起始标志SB置位 */
	I2C_SendData(I2Cx,Addr&0xfe);                       /* 发送从机地址+写位（最低位清0表示写方向） */
	while(I2C_GetFlagStatus(I2Cx,I2C_FLAG_ADDR)==RESET)  /* 等待地址发送完成ADDR标志 */
	{
		/* 判断：地址阶段收到应答失败AF，发停止信号并返回-1 */
		if(I2C_GetFlagStatus(I2Cx,I2C_FLAG_AF)==SET)
		{ I2C_GenerateSTOP(I2Cx,ENABLE); return -1; }
	}
	(void)I2Cx->SR1; (void)I2Cx->SR2;                   /* 读SR1、SR2以硬件清除ADDR地址标志 */

	/* 循环：逐字节发送Size个数据 */
	for(i=0;i<Size;i++)
	{
		while(I2C_GetFlagStatus(I2Cx,I2C_FLAG_TXE)==RESET)  /* 等待发送缓冲空TXE */
		{
			/* 判断：数据阶段应答失败AF，发停止信号并返回-2 */
			if(I2C_GetFlagStatus(I2Cx,I2C_FLAG_AF)==SET)
			{ I2C_GenerateSTOP(I2Cx,ENABLE); return -2; }
		}
		I2C_SendData(I2Cx,pData[i]);                     /* 发送第i个数据字节 */
	}
	while(I2C_GetFlagStatus(I2Cx,I2C_FLAG_BTF)==RESET);  /* 等待最后一个字节传输完成BTF */
	I2C_GenerateSTOP(I2Cx,ENABLE);                      /* 发送停止信号，结束通信 */
	return 0;                                            /* 成功返回0 */
}

/*==================== OLED写命令/写数据 ====================*/
/* 函数：OLED_Write_Cmd —— 向SSD1306写一条命令；控制字节0x00表示后续是命令 */
static void OLED_Write_Cmd(uint8_t cmd)
{
	uint8_t buf[2];
	buf[0]=0x00;     /* 控制字节0x00：标记接下来发送的是命令字节 */
	buf[1]=cmd;
	My_I2C_SendBytes(I2C1,OLED_ADDR,buf,2);
}
/* 函数：OLED_Write_Data —— 向SSD1306写一个显示数据；控制字节0x40表示后续是显示数据 */
static void OLED_Write_Data(uint8_t dat)
{
	uint8_t buf[2];
	buf[0]=0x40;     /* 控制字节0x40：标记接下来发送的是显示数据字节 */
	buf[1]=dat;
	My_I2C_SendBytes(I2C1,OLED_ADDR,buf,2);
}

